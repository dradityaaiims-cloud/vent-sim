// ---- goal evaluation ----
const OPS = { '<': (a, b) => a < b, '<=': (a, b) => a <= b, '>': (a, b) => a > b, '>=': (a, b) => a >= b, '==': (a, b) => a === b };
export function evalGoals(goals, sim) {
  const m = sim.metrics();
  return goals.map((g) => {
    const val = g.k.startsWith('s.') ? sim.set[g.k.slice(2)] : m[g.k];
    return { ...g, val, ok: Number.isFinite(val) || typeof val === 'string' ? OPS[g.op](val, g.v) : false };
  });
}

// Shared by the app and tests. Events (sc.events) are applied by the caller as sim time passes.
export function loadScenario(sc, sim) {
  sim.load(sc.patient.preset, sc.patient.mods, sc.settings);
  sim.settle();
  return sim;
}
